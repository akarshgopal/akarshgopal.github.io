# Builds src/lib/solardata.js from research files in /workspace/research/data/solar (see README for sources).
import json, os
R='/workspace/research/data/solar'
out={}
sq=json.load(open(f'{R}/sq.json'))
out['spec']=sq['spec']                    # ASTM G173-03 global tilt, 10-nm bins [nm, W/m2/nm]
out['sq']=[[r['Eg'],r['below'],r['thermal'],r['eff'],r['Jsc'],r['Voc']] for r in sq['tab']]
if os.path.exists(f'{R}/pvgis_series.json'):
    cs=json.load(open(f'{R}/pvgis_series.json'))
    out['cities']=[[c['name'],c['lat'],c['lon'],c['fixed'],c['track'],c.get('tilt'),c['fixed_monthly'],c['track_monthly'],c['db']] for c in cs if c.get('fixed') and c.get('track')]
hourly={}
for site in ('Seville','Berlin'):
    for k in ('fixed','track'):
        f=f'{R}/hourly_{site}_{k}_2020.json'
        if os.path.exists(f):
            d=json.load(open(f)); hourly[f'{site}_{k}']=[round(p) for p in d['P']]   # W per kWp, hourly, 2020 (UTC)
out['hourly']=hourly
# German capture and summer price profile: Bundesnetzagentur SMARD (CC BY 4.0), via scripts/smard_compute.py.
import sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import smard_compute as SM
_sm = SM.build()
out['capture'] = _sm['solarCapture']          # [year, base, solar price, negative hours, solar TWh]
prof = {int(y): v for y, v in _sm['profile'].items()}   # April–September means by local clock hour (Europe/Berlin)
out['profile']=prof
open('/workspace/electricity-explainer/src/lib/solardata.js','w').write('// Generated by scripts/make_solar_data.py — do not edit by hand.\nexport const SOLAR = '+json.dumps(out,separators=(',',':'))+';\n')
print({k:(len(v) if hasattr(v,'__len__') else v) for k,v in out.items()})
