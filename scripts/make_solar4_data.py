#!/usr/bin/env python3
"""Build src/lib/solar4data.js: solar in the four countries of the series, 2010-2025.

Source: Ember, Yearly electricity data (CC BY 4.0), as extracted for the
restructure pass into ember_4countries.json (keys "Category|Subcategory|Variable|Unit").
Run: python3 -P scripts/make_solar4_data.py [path/to/ember_4countries.json]

share: solar's share of the country's generation, per cent (Ember).
twh:   solar generation, TWh (Ember; includes rooftop where Ember estimates it).
gw:    solar capacity at year end, GW (Ember).
"""
import json, os, sys, hashlib

RAW = sys.argv[1] if len(sys.argv) > 1 else '/tmp/claude-0/-home-user/dc1887ca-8d3b-53f9-b152-28a6e4446aaa/scratchpad/r3data/ember_4countries.json'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'lib', 'solar4data.js')
Y0, Y1 = 2010, 2025
KEYS = {'share': 'Electricity generation|Fuel|Solar|%', 'twh': 'Electricity generation|Fuel|Solar|TWh', 'gw': 'Capacity|Fuel|Solar|GW'}
CODES = {'CN': 'china', 'US': 'us', 'IN': 'india', 'DE': 'germany', 'World': 'world'}

raw = open(RAW, 'rb').read()
d = json.loads(raw)
out = {'years': [Y0, Y1], 'source': 'Ember, Yearly electricity data, 2026 (CC BY 4.0)', 'sha256': hashlib.sha256(raw).hexdigest()[:16]}
for code, name in CODES.items():
    y = d['yearly'][code]
    row = {}
    for k, key in KEYS.items():
        ser = y.get(key)
        if ser is None:
            continue
        nd = 2 if k == 'share' else 1
        row[k] = [round(float(ser[str(yr)]), nd) if ser.get(str(yr)) is not None else None for yr in range(Y0, Y1 + 1)]
    out[name] = row
with open(OUT, 'w') as f:
    f.write('// Generated by scripts/make_solar4_data.py — do not edit by hand.\n')
    f.write('// Ember, Yearly electricity data (CC BY 4.0): solar share of generation (%), generation (TWh) and capacity (GW), 2010–2025.\n')
    f.write('export const SOLAR4 = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print({k: (v if not isinstance(v, dict) else {kk: vv[-1] for kk, vv in v.items()}) for k, v in out.items()})
