# Generates src/lib/winddata.js for the utility-scale renewables post.
# Germany: Bundesnetzagentur SMARD (CC BY 4.0), filters 251/4169 (day-ahead price),
#   4068 (solar), 4067 (onshore), 1225 (offshore), 410 (load); see scripts/smard_compute.py.
# Spain (Seville hybrid only): Red Eléctrica apidatos peninsular spot price 2023; PVGIS (JRC) tracker output.
import json, sys, os
sys.path.insert(0, os.path.dirname(__file__))
import smard_compute as S
d = S.build()
h = d['de2025']
de = {'P': h['P'], 'wind': h['wind'], 'solar': h['solar'], 'load': h['load'], 't0': h['t0'] // 3600000}
hy = d['hybrid']
out = {'capture': d['capture'], 'monthly': d['monthly'], 'de2025': de,
       'hybrid': {'pv': [round(x) for x in hy['pv']], 'price': [round(0.0 if p is None else p, 1) for p in hy['price']]}}
open('src/lib/winddata.js', 'w').write('// Generated by scripts/make_wind_data.py — SMARD (Bundesnetzagentur, CC BY 4.0), Red Eléctrica apidatos and PVGIS (JRC). See utility-renewables.html notes.\nexport const WIND = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('t0', de['t0'], 'hy t0', hy.get('t0'), 'missing', hy.get('missing'), {k: sum(v) for k, v in d['monthly'].items()})
