# Share of population with access to electricity, from Our World in Data (World Bank WDI EG.ELC.ACCS.ZS), CC BY 4.0.
# Raw: /workspace/research/data/global/wb/owid_access.csv
# Source: https://ourworldindata.org/grapher/share-of-the-population-with-access-to-electricity
import csv, json
SRC = '/workspace/research/data/global/wb/owid_access.csv'
WANT = ['World', 'China', 'Vietnam', 'Indonesia', 'India', 'Bangladesh', 'Pakistan', 'Brazil', 'South Africa', 'Nigeria', 'Kenya', 'Ethiopia', 'Democratic Republic of Congo', 'Sub-Saharan Africa (WB)']
d = {}
for r in csv.DictReader(open(SRC)):
    if r['entity'] in WANT and r['eg_elc_accs_zs']:
        d.setdefault(r['entity'], {})[int(r['year'])] = round(float(r['eg_elc_accs_zs']), 1)
missing = [w for w in WANT if w not in d]
print('missing', missing)
out = {k: sorted(v.items()) for k, v in d.items()}
open('src/lib/accessdata.js', 'w').write('// Generated by scripts/make_access_data.py — OWID / World Bank WDI EG.ELC.ACCS.ZS (CC BY 4.0). % of population with electricity.\nexport const ACCESS = ' + json.dumps(out) + ';\n')
for k, v in out.items(): print(k, v[0], v[-1])
