#!/usr/bin/env python3
"""Builds src/lib/txdata.js for the transmission post.

Sources (raw files in /workspace/research/data/tx/):
  fnm2025.pdf  ACEG & Grid Strategies, "Fewer New Miles" (July 2025), Figure 1 (miles of new 345 kV+ lines per year).
               Bars are digitised from the PDF's vector drawing (pdfplumber); calibrated on the axis labels.
               2023 and 2024 are then replaced by the FERC-revised totals given in the report's addendum.
  bnetza_nem2022.pdf  BNetzA, Netzengpassmanagement Gesamtjahr 2022, Tabelle 2 (2017-2022).
  SMARD article "Volumen und Kosten gesunken" (2023, 2024 preliminary) and Bundestag hib 689/2026
  (2024 and 2025 final) for later years.
  mr2025en.pdf  BNetzA/BKartA Monitoring Report 2025, Table 38 (household price as at 1 April 2025).
"""
import json, os
RAW = '/workspace/research/data/tx'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'lib', 'txdata.js')

def us_miles():
    import pdfplumber
    p = pdfplumber.open(os.path.join(RAW, 'fnm2025.pdf')).pages[4]
    words = {w['text']: w for w in p.extract_words()}
    # y axis: '0' and '4,500' labels; use their vertical centres
    zero = [w for w in p.extract_words() if w['text'] == '0' and w['x0'] < 90][0]
    top = [w for w in p.extract_words() if w['text'] == '4,500'][0]
    y0 = (zero['top'] + zero['bottom']) / 2; y45 = (top['top'] + top['bottom']) / 2
    k = 4500 / (y0 - y45)
    years = sorted([(w['x0'], int(w['text'])) for w in p.extract_words() if w['text'].isdigit() and 2010 <= int(w['text']) <= 2024 and abs(w['top'] - 567) < 3])
    bars = [r for r in p.rects if 5 < r['width'] < 12 and r['height'] > 0.5 and 400 < r['top'] and r['bottom'] < 558 and r['x0'] < 460]
    blue, gold = (0.106, 0.267, 0.537), (0.961, 0.698, 0.122)
    out = {}
    for x, yr in years:
        col = [r for r in bars if abs(r['x0'] - x) < 8]
        near = lambda c, ref: c and len(c) == 3 and all(abs(a - b) < 0.01 for a, b in zip(c, ref))
        b = sum(r['height'] for r in col if near(r['non_stroking_color'], blue)) * k
        g = sum(r['height'] for r in col if near(r['non_stroking_color'], gold)) * k
        out[yr] = [round(b), round(g)]
    out[2023] = [400, 50]    # FERC revision (report addendum)
    out[2024] = [334, 554]
    return [[y] + out[y] for y in sorted(out)]

# German congestion management costs, million EUR: [year, redispatch of market plants incl. curtailed renewables, reserve plants (standby + dispatch), countertrading, final?]
NEM = [
    [2017, 391.6 + 609.9, 183.9 + 296.1, 29.0, 1],
    [2018, 388.2 + 635.4, 137.3 + 278.5, 37.2, 1],
    [2019, 227.2 + 709.5, 81.6 + 196.5, 64.2, 1],
    [2020, 240.1 + 761.2, 100.0 + 196.4, 134.7, 1],
    [2021, 589.7 + 807.1, 249.2 + 242.9, 396.7, 1],
    [2022, 2689.2 + 148.0, 650.4 + 389.2, 371.1, 1],
    [2023, 1882 + 580, 353 + 343, 177, 0],
    [2024, 1230 + 554, 696 + 372, 98, 1],
    [2025, 1180 + 435, 955 + 412, 96, 1],
]
# of which compensation to curtailed renewables (EinsMan / RD 2.0), where reported
NEM_EE = {2017: 609.9, 2018: 635.4, 2019: 709.5, 2020: 761.2, 2021: 807.1, 2023: 580, 2024: 554, 2025: 435}

BILL = [  # ct/kWh, household 2,500-5,000 kWh, 1 April 2025, all contract categories
    ['Energy procurement', 11.39, 'energy'], ['Distribution and margin', 4.45, 'energy'],
    ['Net network tariff', 11.02, 'network'], ['Meter operation', 0.48, 'network'],
    ['Offshore network surcharge', 0.82, 'network'], ['Section 19 StromNEV surcharge', 1.56, 'network'],
    ['Concession fees', 1.60, 'levy'], ['CHP (KWKG) surcharge', 0.28, 'levy'],
    ['Electricity tax', 2.05, 'tax'], ['VAT', 6.39, 'tax'],
]

# BNetzA grid-expansion monitoring (netzausbau.de), BBPlG + EnLAG, as at 30 June 2026, km
DEPLAN = [['not yet in approval', 1039], ['spatial planning', 151], ['before or in planning approval', 6437], ['approved or under construction', 4404], ['completed, not yet in operation', 1865], ['in operation', 2983]]

if __name__ == '__main__':
    miles = us_miles()
    for r in miles: print(r)
    js = '// Generated by scripts/make_tx_data.py — do not edit by hand.\n'
    js += 'export const TX = ' + json.dumps({'miles': miles, 'nem': [[r[0], round(r[1], 1), round(r[2], 1), round(r[3], 1), r[4]] for r in NEM], 'nemEE': NEM_EE, 'bill': BILL, 'deplan': DEPLAN}) + ';\n'
    open(OUT, 'w').write(js)
    print('wrote', OUT, sum(r[1] + r[2] + r[3] for r in NEM[-1:]))
