"""Generate src/lib/xfmrdata.js for the Transformers post.
Inputs (raw files in /workspace/research/data/xfmr/):
  bls_all.json  — BLS PPI PCU335311335311 (power, distribution & specialty transformer mfg) and CPI-U CUUR0000SA0, monthly 2006–2026
EU Ecodesign Tier 1/Tier 2 limits are transcribed from Regulation (EU) 548/2014 as amended by 2019/1783, Annex I Table I.1.
"""
import json
R = '/workspace/research/data/xfmr/'
b = json.load(open(R + 'bls_all.json'))
ppi = [[y, m, v] for y, m, v in b['PCU335311335311']]
cpi = [[y, m, v] for y, m, v in b['CUUR0000SA0']]
# Table I.1: three-phase liquid-immersed, Um<=24 kV / <=3.6 kV.  kVA: (Tier1 Pk, Tier1 Po, Tier2 Pk, Tier2 Po) in W
EU = [[25, 900, 70, 600, 63], [50, 1100, 90, 750, 81], [100, 1750, 145, 1250, 130], [160, 2350, 210, 1750, 189],
      [250, 3250, 300, 2350, 270], [315, 3900, 360, 2800, 324], [400, 4600, 430, 3250, 387], [500, 5500, 510, 3900, 459],
      [630, 6500, 600, 4600, 540], [800, 8400, 650, 6000, 585], [1000, 10500, 770, 7600, 693], [1250, 11000, 950, 9500, 855],
      [1600, 14000, 1200, 12000, 1080], [2000, 18000, 1450, 15000, 1305], [2500, 22000, 1750, 18500, 1575], [3150, 27500, 2200, 23000, 1980]]
out = {'ppi': ppi, 'cpi': cpi, 'eu': EU}
open('/workspace/electricity-explainer/src/lib/xfmrdata.js', 'w').write(
    '// Generated by scripts/make_xfmr_data.py — BLS PPI/CPI and EU Ecodesign Reg. 548/2014 Table I.1. See transformers.html notes.\n'
    'export const XF = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(ppi), len(cpi))
