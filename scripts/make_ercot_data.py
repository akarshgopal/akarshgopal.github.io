#!/usr/bin/env python3
"""Builds src/lib/ercotdata.js: a few real days on the Texas grid (ERCOT) for essay 5 (balancing.html, figure ercotDay).

Source: US EIA Form 930 (hourly electric grid monitor), balancing authority ERCO, via Catalyst Cooperative PUDL
(core_eia930__hourly_net_generation_by_energy_source and core_eia930__hourly_operations), adjusted values, MWh per hour,
UTC timestamps, 2024 to September 2026. Raw file: ERCO_hourly_2024_2026.json (downloaded October 2026).

Usage: python3 -P scripts/make_ercot_data.py [path/to/ERCO_hourly_2024_2026.json]

Notes on the raw data:
- Timestamps mark the END of each hour (EIA-930 convention). Checked against solar: the midpoint of the solar day lands at
  about 13:40 local daylight time, close to solar noon over West Texas; read as hour-start it would land an hour late.
- Battery storage: until December 2025 'battery_storage' holds discharge and 'unknown_energy_storage' holds charging
  (negative); from January 2026 'battery_storage' is the net value. Net battery = their sum. Discharge is drawn above zero,
  charging below. Batteries were not reported separately before October 2024.
- Wind and solar moved to the '..._wo_integrated_battery_storage' columns in mid-2024; the two columns are summed.
- 'interchange' is net exports (positive = out of ERCOT); negative values are drawn as imports.
- Hourly MWh equals average MW over the hour; values are written in GW, one decimal.
"""
import json, os, sys, datetime, zoneinfo

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'ERCO_hourly_2024_2026.json')
OUT = os.path.join(HERE, '..', 'src', 'lib', 'ercotdata.js')
TZ = zoneinfo.ZoneInfo('America/Chicago')

# The days offered in the figure, chosen from the whole record by the criteria in 'why'.
DAYS = [
    ('spring', '2026-03-22', 'Spring Sunday', 'among the days with the highest instantaneous wind and solar share of demand in the record (85 per cent)'),
    ('summer', '2026-07-22', 'Summer peak', 'the highest hourly demand in the record'),
    ('winter', '2025-02-20', 'Winter peak', 'the highest winter demand in the record'),
]

G = lambda v, *f: sum((v.get(x) or 0) for x in f)


def series(v):
    bat = G(v, 'battery_storage', 'unknown_energy_storage')
    inter = v.get('interchange') or 0
    return {
        'other': G(v, 'hydro', 'hydro_excluding_pumped_storage', 'other', 'oil', 'geothermal', 'unknown', 'pumped_storage', 'other_energy_storage'),
        'wind': G(v, 'wind', 'wind_w_integrated_battery_storage', 'wind_wo_integrated_battery_storage'),
        'solar': G(v, 'solar', 'solar_w_integrated_battery_storage', 'solar_wo_integrated_battery_storage'),
        'nuclear': G(v, 'nuclear'),
        'coal': G(v, 'coal'),
        'gas': G(v, 'gas'),
        'storage': max(0, bat),
        'imports': max(0, -inter),
        'charge': max(0, -bat),
        'exports': max(0, inter),
        'demand': v['demand'],
    }


def main():
    hours = json.load(open(RAW))['hours']
    byday = {}
    for k, v in hours.items():
        end = datetime.datetime.fromisoformat(k).replace(tzinfo=datetime.timezone.utc).astimezone(TZ)
        start = end - datetime.timedelta(hours=1)
        byday.setdefault(start.date().isoformat(), {})[start.hour] = v
    out = []
    for key, date, label, why in DAYS:
        d = byday[date]
        assert sorted(d) == list(range(24)), (date, sorted(d))
        rows = [series(d[h]) for h in range(24)]
        # sanity: generation (net of charging) = demand + net exports, within 1 per cent
        for r in rows:
            gen = sum(r[k] for k in ('other', 'wind', 'solar', 'nuclear', 'coal', 'gas', 'storage', 'imports')) - r['charge'] - r['exports']
            assert abs(gen - r['demand']) < 0.01 * r['demand'], (date, gen, r['demand'])
        S = {k: [round(r[k] / 1000, 1) for r in rows] for k in rows[0]}
        out.append({'key': key, 'date': date, 'label': label, 'why': why,
                    'weekday': datetime.date.fromisoformat(date).strftime('%A'), **S})
    js = ('// Generated by scripts/make_ercot_data.py from US EIA Form 930 (via Catalyst Cooperative PUDL) — do not edit by hand.\n'
          '// Hourly average generation by source, demand, battery charging and net exports for the Texas grid (ERCOT), GW,\n'
          '// local time (Central), index = hour starting 00:00 … 23:00.\n'
          'export const ERCOT_DAYS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    open(OUT, 'w').write(js)
    print('wrote', OUT, len(js), 'bytes')
    for o in out:
        dem = o['demand']; vre = [w + s for w, s in zip(o['wind'], o['solar'])]
        i = dem.index(max(dem)); j = max(range(24), key=lambda h: vre[h] / dem[h])
        print(o['date'], o['label'], 'peak demand %.1f GW at %02d:00' % (dem[i], i),
              '| max wind+solar share %.0f%% at %02d:00' % (100 * vre[j] / dem[j], j),
              '| day wind+solar %.0f%%' % (100 * sum(vre) / sum(dem)), '| gas day %.0f%%' % (100 * sum(o['gas']) / sum(dem)),
              '| batt max %.1f GW at %02d:00' % (max(o['storage']), o['storage'].index(max(o['storage']))),
              '| charge max %.1f' % max(o['charge']), '| gas at peak %.1f' % o['gas'][i])


if __name__ == '__main__':
    main()
