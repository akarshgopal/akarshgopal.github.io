#!/usr/bin/env python3
"""Build src/lib/cheaperdata.js for essay 1 (cheaper.html) from Our World in Data's energy dataset.

Source (CC BY 4.0): https://github.com/owid/energy-data (owid-energy-data.csv), saved at RAW.
OWID compiles electricity from Ember (2000 onwards) and the Energy Institute Statistical Review (before 2000).
Columns used: per_capita_electricity (generation per person, kWh) and electricity_generation (TWh).
Run: python3 -P scripts/make_cheaper_data.py [path to owid-energy.csv]
"""
import csv, hashlib, json, os, sys

RAW = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/data/owid-energy.csv')
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'lib', 'cheaperdata.js')
Y0, Y1 = 1985, 2025
AREAS = [('us', 'United States'), ('de', 'Germany'), ('cn', 'China'), ('in', 'India'), ('world', 'World')]

rows = list(csv.DictReader(open(RAW, newline='', encoding='utf-8')))
sha = hashlib.sha256(open(RAW, 'rb').read()).hexdigest()
out = {'years': [Y0, Y1]}
for key, name in AREAS:
    by = {int(r['year']): r for r in rows if r['country'] == name}
    pc, gen = [], []
    for y in range(Y0, Y1 + 1):
        r = by[y]
        pc.append(round(float(r['per_capita_electricity'])))
        gen.append(round(float(r['electricity_generation']), 1))
    out[key] = {'perCap': pc, 'gen': gen}

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('// Generated by scripts/make_cheaper_data.py — do not edit by hand.\n')
    f.write('// Our World in Data, energy dataset (from Ember and the Energy Institute Statistical Review), CC BY 4.0.\n')
    f.write(f'// sha256 of the CSV: {sha}\n')
    f.write(f'// One value per year {Y0}..{Y1}. perCap: electricity generated per person, kWh. gen: total generation, TWh.\n')
    f.write('export const USE = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print('wrote', OUT)
