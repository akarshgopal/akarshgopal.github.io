#!/usr/bin/env python3
"""Build src/lib/seasonsdata.js: monthly wind, solar and demand for the US, Germany, China and India.

Source: Ember, Monthly electricity data (CC BY 4.0), as extracted for the October 2026 restructure into
ember_4countries.json (keys "Category|Subcategory|Variable|Unit"). Values are TWh per month, rounded to
0.01 TWh. Only whole years with all twelve months for all four countries are kept (India's monthly
series begins in 2019). Run: python3 -P scripts/make_seasons_data.py <path to ember_4countries.json>
"""
import json, os, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'ember_4countries.json'
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'lib', 'seasonsdata.js')
COUNTRIES = [('US', 'United States'), ('DE', 'Germany'), ('CN', 'China'), ('IN', 'India')]
KEYS = {'wind': 'Electricity generation|Fuel|Wind|TWh', 'solar': 'Electricity generation|Fuel|Solar|TWh',
        'demand': 'Electricity demand|Demand|Demand|TWh'}

with open(SRC) as f:
    d = json.load(f)
mon = d['monthly']

def full(c, y):
    return all(mon[c][k].get(f'{y}-{m:02d}-01') is not None for k in KEYS.values() for m in range(1, 13))

years = [y for y in range(2015, 2030) if all(full(c, y) for c, _ in COUNTRIES)]
out = {'years': years, 'countries': []}
for c, name in COUNTRIES:
    row = {'id': c, 'name': name}
    for k, key in KEYS.items():
        row[k] = [round(mon[c][key][f'{y}-{m:02d}-01'], 2) for y in years for m in range(1, 13)]
    out['countries'].append(row)

with open(OUT, 'w') as f:
    f.write('// Generated by scripts/make_seasons_data.py — do not edit by hand.\n')
    f.write('// Ember, Monthly electricity data (CC BY 4.0), downloaded 2026-10-21. TWh per month; months run January to\n')
    f.write('// December for each year in `years`, years in order.\n')
    f.write('export const SEASONS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(OUT, years, os.path.getsize(OUT), 'bytes')
