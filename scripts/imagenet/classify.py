"""Run three torchvision ImageNet classifiers (the architectures that won ILSVRC 2012, 2014 and 2015) on the
Commons photos picked by fetch_photos.py, offline on CPU, and write src/lib/imagenetphotos.js with each photo
(centre crop, 160 px JPEG, as data URI), its credit line and each model's real top-5 guesses.

Weights: torchvision IMAGENET1K_V1 for AlexNet, GoogLeNet and ResNet-152. These are torchvision's own
re-trainings of the published architectures, evaluated as single models on a single centre crop, so they are
less accurate than the contest entries (which were ensembles of several models and many crops). torchvision's
note: the weights 'may have their own licenses or terms and conditions derived from the dataset used for
training' (ImageNet: non-commercial research and education). Only the label outputs are published here; no
weights or ImageNet images are redistributed.
Run: /workspace/.venv-ml/bin/python scripts/imagenet/classify.py"""
import json, base64, io, torch
from PIL import Image
from torchvision.models import alexnet, AlexNet_Weights, googlenet, GoogLeNet_Weights, resnet152, ResNet152_Weights
from torchvision.transforms import functional as TF
torch.set_num_threads(8)
MODELS = [('AlexNet', 2012, alexnet, AlexNet_Weights.IMAGENET1K_V1), ('GoogLeNet', 2014, googlenet, GoogLeNet_Weights.IMAGENET1K_V1),
          ('ResNet-152', 2015, resnet152, ResNet152_Weights.IMAGENET1K_V1)]
photos = json.load(open('research/imagenet-photos.json'))
cats = AlexNet_Weights.IMAGENET1K_V1.meta['categories']
for p in photos: assert p['cls'] in cats, p['cls']
def crop(im):  # the same resize-256 / centre-crop-224 that the models' evaluation transform uses
    im = TF.resize(im, 256); return TF.center_crop(im, 224)
out = {'models': [], 'photos': []}
ims = [Image.open(p['file']).convert('RGB') for p in photos]
for name, year, fn, w in MODELS:
    m = fn(weights=w).eval(); tf = w.transforms()
    with torch.no_grad(): P = m(torch.stack([tf(im) for im in ims])).softmax(-1)
    top = P.topk(5, -1)
    out['models'].append({'name': name, 'year': year, 'weights': str(w), 'valTop5Err': round(100 - w.meta['_metrics']['ImageNet-1K']['acc@5'], 2),
                          'params': sum(x.numel() for x in m.parameters())})
    for i, p in enumerate(photos):
        p.setdefault('guess', []).append([[cats[j], round(v, 3)] for v, j in zip(top.values[i].tolist(), top.indices[i].tolist())])
    print(name, 'right in top 5:', sum(p['cls'] in [g[0] for g in p['guess'][-1]] for p in photos), '/', len(photos),
          '| top 1:', sum(p['cls'] == p['guess'][-1][0][0] for p in photos))
for p, im in zip(photos, ims):
    b = io.BytesIO(); crop(im).resize((160, 160), Image.LANCZOS).save(b, 'JPEG', quality=72, optimize=True, progressive=True)
    out['photos'].append({'cls': p['cls'], 'img': 'data:image/jpeg;base64,' + base64.b64encode(b.getvalue()).decode(),
                          'author': p['author'], 'licence': p['licence'], 'url': p['url'], 'title': p['title'][5:], 'guess': p['guess']})
js = ('// Generated by scripts/imagenet/classify.py: freely licensed Wikimedia Commons photos and the real top-5 guesses of\n'
      '// torchvision AlexNet, GoogLeNet and ResNet-152 (IMAGENET1K_V1), run offline. guess[model][k] = [label, probability].\n'
      'export const INPHOTOS = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n')
open('src/lib/imagenetphotos.js', 'w').write(js); print('wrote', len(js), 'bytes')
for p in out['photos']: print(p['cls'], '|', ' / '.join(g[0][0] + (' ✓' if p['cls'] in [x[0] for x in g] else ' ✗') for g in p['guess']))
