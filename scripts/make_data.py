import csv, json
D='/workspace/research/data/'
out={}
# Lazard LCOE
laz={}
for r in csv.DictReader(open(D+'lazard_lcoe.csv')):
    laz.setdefault(r['technology_id'],[]).append([int(r['year']),float(r['lcoe_low']),float(r['lcoe_high'])])
out['lazard']=laz
out['lazardLcos']=[dict(year=int(r['year']),config=r['config'],low=float(r['lcos_low']),high=float(r['lcos_high'])) for r in csv.DictReader(open(D+'lazard_lcos.csv'))]
# BDEW
out['bdew']=[[int(r['year']),float(r['procurement_sales_ct_per_kwh']),float(r['network_ct']),float(r['taxes_levies_ct']),float(r['total_ct'])] for r in csv.DictReader(open(D+'bdew_hh_stack.csv'))]
# Ember
out['emberAnnual']=[[int(r['year']),float(r['avg_dayahead_eur_mwh'])] for r in csv.DictReader(open(D+'ember_de_annual.csv'))]
out['emberMonthly']=[[r['Date'][:7],float(r['Price (EUR/MWhe)'])] for r in csv.DictReader(open(D+'ember_monthly.csv')) if r['Country']=='Germany']
# OWID world
ow={'solar':[], 'onshore':[], 'offshore':[]}
for r in csv.DictReader(open(D+'owid_lcoe.csv')):
    if r['Entity']=='World':
        y=int(r['Year'])
        for k,col in [('solar','Solar photovoltaic'),('onshore','Onshore wind'),('offshore','Offshore wind')]:
            if r[col]: ow[k].append([y, round(float(r[col])*1000,1)])
out['owidWorld']=ow
open('src/lib/data.js','w').write('// Generated by scripts/make_data.py from /workspace/research/data — do not edit by hand.\nexport const DATA = '+json.dumps(out)+';\n')
print(len(out['emberMonthly']), {k:len(v) for k,v in laz.items()})
