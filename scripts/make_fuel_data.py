"""Build src/lib/fueldata.js for Part 5 (synthetic fuels).
Prices: SMARD (Bundesnetzagentur) day-ahead DE-LU, filter 4169, hourly, 2025 (CC BY 4.0).
Raw: /workspace/research/data/fuels/smard_4169_2025.json (downloaded from smard.de/app/chart_data)."""
import json, datetime
RAW = '/workspace/research/data/fuels/smard_4169_2025.json'
d = json.load(open(RAW))
rows = sorted((int(k), v) for k, v in d.items())
raw25 = [v for ts, v in rows if datetime.datetime.fromtimestamp(ts / 1000).year == 2025]
p25 = [round(v) for v in raw25]
assert len(p25) == 8760, len(p25)
FUEL = {
  'prices': p25,
  'priceMean': round(sum(v for ts, v in rows if datetime.datetime.fromtimestamp(ts/1000).year == 2025) / 8760, 1),
  'negHours': sum(1 for v in raw25 if v < 0), 'zeroOrNeg': sum(1 for v in raw25 if v <= 0), 'le20': sum(1 for v in raw25 if v <= 20),
  # DOE Hydrogen Shot water electrolysis technology assessment (Dec 2024), Table 2 + appendix: status values, kWh/kg H2
  'elec': [
    {'k': 'alk', 'name': 'Alkaline', 'stack': 51, 'sysBOL': 55, 'sysAvg': 57.3, 'heat': 0, 'T': '70–90 °C', 'capex': 'cheapest; nickel electrodes, no precious metals'},
    {'k': 'pem', 'name': 'PEM', 'stack': 51, 'sysBOL': 55.2, 'sysAvg': 57.5, 'heat': 0, 'T': '50–80 °C', 'capex': 'compact, fast-ramping; platinum and iridium'},
    {'k': 'soec', 'name': 'Solid oxide (SOEC)', 'stack': 34, 'sysBOL': 38, 'sysAvg': 40, 'heat': 9, 'T': '700–850 °C', 'capex': 'needs steam and heat; ramps slowly'},
  ],
  'lhv': 33.33, 'hhv': 39.41,
  'ieaAvg': round(33.33 / 0.63, 1), 'ieaChina': round(33.33 / 0.58, 1), 'inlRecord': 36.7,
  # European Hydrogen Bank auctions (European Commission)
  'ehb': [
    {'n': 'Pilot auction (IF23), Apr 2024', 'projects': 7, 'gw': 1.5, 'eur': 720, 'lo': 0.37, 'hi': 0.48},
    {'n': 'Second auction (IF24), May 2025', 'projects': 15, 'gw': 2.3, 'eur': 992, 'lo': 0.20, 'hi': 0.60},
  ],
}
# Presets for cheapHours: other systems' hourly day-ahead/spot prices, converted to EUR/MWh.
#  South Australia 2025: AEMO NEM "Aggregated price and demand data", SA1, 5-minute RRP (A$/MWh), averaged to 8,760 hours
#   (NEM time, UTC+10, no DST); converted at the ECB 2025 average 1.75176 AUD/EUR. Raw: /workspace/research/data/global/aemo/sa_2025MM.csv
#  Spain 2023: Red Eléctrica apidatos peninsular spot (EUR/MWh), from scripts/smard_compute.py (same series as the Seville hybrid).
import csv, glob, os, sys
from collections import defaultdict
acc = defaultdict(list)
for f in sorted(glob.glob('/workspace/research/data/global/aemo/sa_2025*.csv')):
    for r in csv.DictReader(open(f)):
        t = datetime.datetime.strptime(r['SETTLEMENTDATE'], '%Y/%m/%d %H:%M:%S') - datetime.timedelta(minutes=5)  # interval-ending
        if t.year == 2025: acc[(t.month, t.day, t.hour)].append(float(r['RRP']))
sa = [round(sum(v) / len(v) / 1.75176) for k, v in sorted(acc.items())]
assert len(sa) == 8760, len(sa)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import smard_compute as SM
es = [round(0.0 if v is None else v) for v in SM.build()['hybrid']['price']]
FUEL['presets'] = {'sa': {'prices': sa, 'mean': round(sum(sa) / 8760, 1)}, 'es': {'prices': es, 'mean': round(sum(es) / 8760, 1)}}
print('SA mean', FUEL['presets']['sa']['mean'], 'neg', sum(1 for v in sa if v < 0), 'ES mean', FUEL['presets']['es']['mean'], 'zero', sum(1 for v in es if v <= 0))
open('src/lib/fueldata.js', 'w').write('// generated by scripts/make_fuel_data.py — do not edit\nexport const FUEL = ' + json.dumps(FUEL, separators=(',', ':'), ensure_ascii=False) + ';\n')
print(FUEL['priceMean'], FUEL['negHours'], FUEL['zeroOrNeg'], FUEL['ieaAvg'], FUEL['ieaChina'])
