"""Builds src/lib/aidata.js from CC BY sources in research/raw/.
Epoch AI (CC BY): notable_ai_models.csv, ml_hardware.csv. Karl Rupp, Microprocessor Trend Data (CC BY 4.0): 50yrs/*.dat.
Run: python3 scripts/make_ai_data.py"""
import csv, json, datetime, os
R = 'research/raw/'
def yr(s):
    d = datetime.date.fromisoformat(s[:10]); return round(d.year + (d.timetuple().tm_yday - 0.5) / 365.25, 3)
CC = {'United States of America': 'US', 'China': 'CN', 'United Kingdom': 'UK', 'South Korea': 'KR', 'Germany': 'DE', 'Canada': 'CA',
      'Japan': 'JP', 'Switzerland': 'CH', 'Israel': 'IL', 'France': 'FR', 'Netherlands': 'NL', 'Saudi Arabia': 'SA', 'United Arab Emirates': 'AE',
      'India': 'IN', 'Russia': 'RU', 'Singapore': 'SG', 'Taiwan': 'TW', 'Finland': 'FI', 'Poland': 'PL', 'Australia': 'AU', 'Italy': 'IT', 'Spain': 'ES', 'Sweden': 'SE'}
models = []
for x in csv.DictReader(open(R + 'notable_ai_models.csv', encoding='utf-8')):
    c = x['Training compute (FLOP)']; d = x['Publication date']
    if not c or not d: continue
    ctry = [CC.get(k.strip(), 'other') for k in x['Country (of organization)'].split(',') if k.strip()]
    models.append([yr(d), float('%.3g' % float(c)), x['Model'], x['Organization'].split(',')[0][:40], ctry[0] if ctry else '', x['Domain'].split(',')[0], 1 if x['Frontier model'] == 'True' else 0])
models.sort()
hw = []
for x in csv.DictReader(open(R + 'ml_hardware.csv', encoding='utf-8')):
    f16 = x['Tensor-FP16/BF16 performance (FLOP/s)']; f32 = x['FP32 (single precision) performance (FLOP/s)']; tdp = x['TDP (W)']; d = x['Release date']
    if not tdp or not d or not (f16 or f32): continue
    hw.append([yr(d), x['Hardware name'], x['Manufacturer'], float(f16) if f16 else None, float(f32) if f32 else None, float(tdp), x['Type']])
hw.sort()

def num(v):
    try: return float(v)
    except: return None
hw2 = []
for x in csv.DictReader(open(R + 'ml_hardware.csv', encoding='utf-8')):
    d = x['Release date']; f16 = num(x['Tensor-FP16/BF16 performance (FLOP/s)']); bw = num(x['Memory bandwidth (byte/s)'])
    if not d or not f16 or not bw: continue
    hw2.append([yr(d), x['Hardware name'], x['Manufacturer'], f16, num(x['FP8 performance (FLOP/s)']), num(x['FP4 performance (FLOP/s)']), bw, num(x['Intranode bandwidth (byte/s)']), num(x['Internode bandwidth (bit/s)']), num(x['TDP (W)']), x['Type']])
hw2.sort()
lang = []
for x in csv.DictReader(open(R + 'notable_ai_models.csv', encoding='utf-8')):
    d = x['Publication date']; n = num(x['Parameters']); ds = num(x['Training dataset size (total)']); c = num(x['Training compute (FLOP)'])
    if not d or 'Language' not in x['Domain'] or not ds: continue
    ctry = [CC.get(k.strip(), 'other') for k in x['Country (of organization)'].split(',') if k.strip()]
    lang.append([yr(d), x['Model'], x['Organization'].split(',')[0][:40], ctry[0] if ctry else '', float('%.3g' % n) if n else None, float('%.3g' % ds), float('%.3g' % c) if c else None])
lang.sort()
def dat(n): return [[round(float(a), 3), float('%.4g' % float(b))] for a, b in (l.split()[:2] for l in open(R + f'rupp_{n}.dat') if len(l.split()) >= 2 and not l.startswith('#'))]
rupp = {k: dat(k) for k in ['transistors', 'frequency', 'watts', 'cores', 'specint']}
out = ['// Generated by scripts/make_ai_data.py. Do not edit.',
       '// Epoch AI, "Notable AI Models" and "Machine Learning Hardware" (CC BY), downloaded ' + datetime.date.today().isoformat() + ' from epoch.ai/data.',
       '// Karl Rupp, "Microprocessor Trend Data" (CC BY 4.0), github.com/karlrupp/microprocessor-trend-data, 50yrs/*.dat.',
       '// MODELS: [year, training FLOP, name, organisation, country code, domain, frontier flag]',
       'export const MODELS = ' + json.dumps(models, ensure_ascii=False, separators=(',', ':')) + ';',
       '// HW: [year, name, manufacturer, FP16/BF16 tensor FLOP/s, FP32 FLOP/s, TDP W, type]',
       'export const HW = ' + json.dumps(hw, ensure_ascii=False, separators=(',', ':')) + ';',
       '// RUPP: transistors (thousands), frequency (MHz), watts (typical power, W), cores, specint (single-thread, x1000)',
       '// HW2: [year, name, manufacturer, BF16 FLOP/s, FP8, FP4, memory bandwidth B/s, intranode B/s, internode bit/s, TDP W, type]',
       'export const HW2 = ' + json.dumps(hw2, ensure_ascii=False, separators=(',', ':')) + ';',
       '// LANG: language models with dataset size: [year, name, organisation, country, parameters, dataset size (datapoints, mostly tokens), training FLOP]',
       'export const LANG = ' + json.dumps(lang, ensure_ascii=False, separators=(',', ':')) + ';',
       'export const RUPP = ' + json.dumps(rupp, separators=(',', ':')) + ';']
open('src/lib/aidata.js', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(len(models), 'models', len(hw), 'chips', os.path.getsize('src/lib/aidata.js'), 'bytes')
